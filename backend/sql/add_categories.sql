CREATE TABLE IF NOT EXISTS categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    family VARCHAR(100) NOT NULL
);

-- ============================================================
-- 2. CATÉGORIES DÉTECTÉES POUR CHAQUE DOCUMENT
-- ============================================================

CREATE TABLE IF NOT EXISTS document_categories (
    document_id INTEGER NOT NULL,
    category_id INTEGER NOT NULL,

    PRIMARY KEY (document_id, category_id),

    CONSTRAINT fk_document_categories_document
        FOREIGN KEY (document_id)
        REFERENCES documents(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_document_categories_category
        FOREIGN KEY (category_id)
        REFERENCES categories(id)
        ON DELETE CASCADE
);

-- ============================================================
-- 3. CATÉGORIE PRINCIPALE DE CHAQUE CHUNK
-- ============================================================

ALTER TABLE document_chunks
ADD COLUMN IF NOT EXISTS category_id INTEGER;

-- ============================================================
-- 4. CLÉ ÉTRANGÈRE
-- ============================================================

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_document_chunks_category'
    ) THEN

        ALTER TABLE document_chunks
        ADD CONSTRAINT fk_document_chunks_category
        FOREIGN KEY (category_id)
        REFERENCES categories(id)
        ON DELETE RESTRICT;

    END IF;
END
$$;

-- ============================================================
-- 5. INDEX
-- ============================================================

